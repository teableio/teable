import type { ReproTrigger } from './deadLetter';
import type { ReproStructure } from './structure';

export type EmitSpecInput = {
  structure: ReproStructure;
  trigger: ReproTrigger;
  expectation: 'failure' | 'success';
  /** Human label: task id, dead-letter file, or structure source. */
  sourceLabel: string;
  /** Observed error signature to assert; only for `failure`. */
  errorSignature?: string;
  failureKind?: string;
  /** Local fault injection to reproduce the recorded dead letter. */
  fault?: string;
};

const indent = (value: unknown) => JSON.stringify(value, null, 2);

const renderTrigger = (trigger: ReproTrigger) =>
  indent({
    kind: trigger.kind,
    tableId: trigger.tableId,
    fieldIds: trigger.fieldIds,
    fieldUpdate: trigger.fieldUpdate ?? null,
  });

/**
 * Emit a single-file vitest skeleton following the conventions of
 * `adapter-table-repository-postgres/src/record/computed/__tests__/*.pglite.spec.ts`:
 * `createV2NodeTestContainer({ connectionString: 'memory://' })`, core commands,
 * `processOutbox()`, then a dead-letter assertion.
 *
 * The structure is embedded (sanitized) and installed with core commands so the
 * file has no dependency on devtools, DotTea, or a zip fixture.
 */
export const renderPgliteSpec = (input: EmitSpecInput): string => {
  const { structure, trigger, expectation, sourceLabel, errorSignature, failureKind, fault } =
    input;
  const assertion =
    expectation === 'failure'
      ? [
          `    expect(lastError, 'expected the recorded computed failure').toBeTruthy();`,
          errorSignature
            ? `    expect(lastError).toContain(${JSON.stringify(errorSignature)});`
            : '    // TODO: narrow this to the exact Postgres message you are fixing.',
        ].join('\n')
      : `    expect(deadLetters.rows, 'recorded run had no dead letter').toEqual([]);`;

  return `/* eslint-disable @typescript-eslint/naming-convention */
/**
 * Generated by \`teable-devtools repro computed\`.
 *
 * Repro source: ${sourceLabel}
 * Trigger: ${trigger.kind} (${trigger.reason})
 * Recorded outcome: ${expectation}${failureKind ? ` (${failureKind})` : ''}
 *
 * The structure below is sanitized: display names are pseudonyms and no
 * customer cell values are embedded. Field/table ids are the original ids, so
 * the trigger descriptor still addresses the same fields.
 *
 * Run:
 *   pnpm --filter @teable/v2-adapter-table-repository-postgres exec vitest run \\
 *     src/record/computed/__tests__/<this-file>.pglite.spec.ts
 */
import {
  createV2NodeTestContainer,
  type IV2NodeTestContainer,
} from '@teable/v2-container-node-test';
import {
  ActorId,
  CreateBaseCommand,
  CreateFieldCommand,
  CreateRecordsCommand,
  CreateTableCommand,
  ListTableRecordsQuery,
  UpdateRecordCommand,
  v2CoreTokens,
  type ICommandBus,
  type IExecutionContext,
  type IQueryBus,
} from '@teable/v2-core';
import { sql } from 'kysely';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

type StructureField = {
  id?: string;
  name?: string;
  type: string;
  options?: Record<string, unknown> | null;
  lookupOptions?: Record<string, unknown> | null;
  isPrimary?: boolean;
  notNull?: boolean;
  unique?: boolean;
  dbFieldName?: string;
  cellValueType?: string;
  isMultipleCellValue?: boolean;
};

const STRUCTURE: { tables: Array<{ id?: string; name: string; fields: StructureField[] }> } = ${indent(
    structure
  )};

const TRIGGER = ${renderTrigger(trigger)};
const FAULT = ${fault ? JSON.stringify(fault) : 'null'};

const DEFERRED_FIELD_TYPES: Record<string, true> = {
  link: true,
  lookup: true,
  rollup: true,
  conditionalLookup: true,
  conditionalRollup: true,
};

const asRecord = (value: unknown): Record<string, unknown> => {
  return value && typeof value === 'object' ? (value as Record<string, unknown>) : {};
};

const unwrap = <T>(result: { isErr(): boolean; error?: unknown; value?: T }): T => {
  if (result.isErr()) throw new Error(JSON.stringify(result.error));
  return result.value as T;
};

const fieldInput = (field: StructureField) => {
  const base = {
    id: field.id,
    name: field.name,
    isPrimary: field.isPrimary,
    notNull: field.notNull,
    unique: field.unique,
    dbFieldName: field.dbFieldName,
  };
  const options = asRecord(field.options);
  const lookupOptions = asRecord(field.lookupOptions);

  if (field.type === 'formula') return { ...base, type: field.type, options };
  if (field.type === 'link') return { ...base, type: field.type, options };
  if (field.type === 'lookup') {
    return {
      ...base,
      type: field.type,
      options: lookupOptions,
      innerOptions: options,
      isMultipleCellValue: field.isMultipleCellValue,
    };
  }
  if (field.type === 'rollup') {
    return {
      ...base,
      type: field.type,
      config: lookupOptions,
      options,
      cellValueType: field.cellValueType ?? 'number',
      isMultipleCellValue: field.isMultipleCellValue ?? false,
    };
  }
  if (field.type === 'conditionalLookup') {
    return { ...base, type: field.type, options: lookupOptions };
  }
  if (field.type === 'conditionalRollup') {
    return {
      ...base,
      type: field.type,
      config: lookupOptions,
      options,
      cellValueType: field.cellValueType ?? 'number',
    };
  }
  return { ...base, type: field.type, options };
};

const syntheticValue = (type: string) => {
  switch (type) {
    case 'number':
    case 'rating':
      return 1;
    case 'checkbox':
      return true;
    case 'date':
      return '2026-01-01T00:00:00.000Z';
    case 'singleSelect':
    case 'multipleSelect':
      return type === 'multipleSelect' ? ['Choice_1'] : 'Choice_1';
    default:
      return 'repro row';
  }
};

describe('computed repro (generated)', () => {
  let testContainer: IV2NodeTestContainer;
  let context: IExecutionContext;
  let commandBus: ICommandBus;
  let queryBus: IQueryBus;

  beforeAll(async () => {
    testContainer = await createV2NodeTestContainer({
      connectionString: 'memory://',
      computedUpdate: {
        mode: 'async',
        outboxConfig: { maxAttempts: 1, baseBackoffMs: 0, maxBackoffMs: 0 },
      },
    });
    context = { actorId: unwrap(ActorId.create('repro-spec')) };
    commandBus = testContainer.container.resolve(v2CoreTokens.commandBus) as ICommandBus;
    queryBus = testContainer.container.resolve(v2CoreTokens.queryBus) as IQueryBus;

    const baseResult = unwrap(
      await commandBus.execute(context, unwrap(CreateBaseCommand.create({ name: 'Repro Base' })))
    );
    const baseId = baseResult.base.id().toString();

    // Pass 1: tables with plain and formula fields.
    for (const table of STRUCTURE.tables) {
      const fields = table.fields
        .filter((field) => !DEFERRED_FIELD_TYPES[field.type])
        .map((field) => fieldInput(field) as never);
      const result = await commandBus.execute(
        context,
        unwrap(CreateTableCommand.create({ baseId, tableId: table.id, name: table.name, fields }))
      );
      if (result.isErr()) throw result.error;
    }

    // Pass 2: link fields (foreign tables exist now).
    for (const table of STRUCTURE.tables) {
      for (const field of table.fields.filter((entry) => entry.type === 'link')) {
        const result = await commandBus.execute(
          context,
          unwrap(
            CreateFieldCommand.create({
              baseId,
              tableId: table.id,
              field: fieldInput(field) as never,
            })
          )
        );
        if (result.isErr()) throw result.error;
      }
    }

    // Pass 3: lookup/rollup fields (links exist now).
    for (const table of STRUCTURE.tables) {
      for (const field of table.fields.filter(
        (entry) => entry.type !== 'link' && DEFERRED_FIELD_TYPES[entry.type]
      )) {
        const result = await commandBus.execute(
          context,
          unwrap(
            CreateFieldCommand.create({
              baseId,
              tableId: table.id,
              field: fieldInput(field) as never,
            })
          )
        );
        if (result.isErr()) throw result.error;
      }
    }

    // Rows: three per table, writable fields only.
    for (const table of STRUCTURE.tables) {
      const writable = table.fields.filter(
        (field) =>
          field.type !== 'formula' &&
          field.type !== 'link' &&
          !DEFERRED_FIELD_TYPES[field.type]
      );
      const records = [0, 1, 2].map(() => ({
        fields: Object.fromEntries(
          writable.map((field) => [field.id, syntheticValue(field.type)])
        ),
      }));
      const result = await commandBus.execute(
        context,
        unwrap(
          CreateRecordsCommand.create({
            tableId: table.id,
            fieldKeyType: 'id',
            records,
            typecast: true,
          })
        )
      );
      if (result.isErr()) throw result.error;
    }

    if (FAULT && FAULT.startsWith('column-type-drift:')) {
      const fieldId = FAULT.slice('column-type-drift:'.length);
      const storageRows = await sql<{ schema_name: string; table_name: string; field_name: string }>\`
        select
          split_part(t."db_table_name", '.', 1) as "schema_name",
          split_part(t."db_table_name", '.', 2) as "table_name",
          f."db_field_name" as "field_name"
        from "field" f
        inner join "table_meta" t on t."id" = f."table_id"
        where f."id" = \${fieldId} and f."deleted_time" is null
        limit 1
      \`.execute(testContainer.metaDb);
      const storage = storageRows.rows[0];
      if (!storage) throw new Error(\`fault: field storage not found for \${fieldId}\`);
      const quote = (value: string) => \`"\${value.replaceAll('"', '""')}"\`;
      await sql
        .raw(
          \`alter table \${quote(storage.schema_name)}.\${quote(storage.table_name)} alter column \${quote(
            storage.field_name
          )} type boolean using null\`
        )
        .execute(testContainer.metaDb);
    }

    // Trigger.
    const tableId = TRIGGER.tableId ?? STRUCTURE.tables[0]?.id;
    if (!tableId) throw new Error('trigger has no table');

    if (TRIGGER.kind === 'field-update') {
      // TODO: apply the recorded UpdateFieldCommand payload:
      // await commandBus.execute(context, unwrap(UpdateFieldCommand.create({
      //   tableId: TRIGGER.fieldUpdate!.tableId,
      //   fieldId: TRIGGER.fieldUpdate!.fieldId,
      //   field: TRIGGER.fieldUpdate!.field!,
      // })));
    } else {
      const recordQuery = unwrap(
        await queryBus.execute(
          context,
          unwrap(ListTableRecordsQuery.create({ tableId, fieldKeyType: 'id', limit: 1 }))
        )
      );
      const recordId = recordQuery.records[0]?.id;
      if (!recordId) throw new Error('no record to trigger');

      if (TRIGGER.kind === 'link-change') {
        // TODO: link \`recordId\` to the first record of the link's foreign table.
        expect(TRIGGER.fieldIds[0]).toBeTruthy();
      } else {
        const findField = (fieldId: string) =>
          STRUCTURE.tables.flatMap((table) => table.fields).find((field) => field.id === fieldId);
        const fields = Object.fromEntries(
          TRIGGER.fieldIds.map((fieldId) => {
            const field = findField(fieldId);
            return [fieldId, field ? syntheticValue(field.type) : 'repro trigger'];
          })
        );
        const result = await commandBus.execute(
          context,
          unwrap(
            UpdateRecordCommand.create({
              tableId,
              recordId,
              fieldKeyType: 'id',
              fields,
            })
          )
        );
        if (result.isErr()) throw result.error;
      }
    }

    await testContainer.processOutbox();
  }, 120_000);

  afterAll(async () => {
    if (testContainer) await testContainer.dispose();
  }, 120_000);

  it('reproduces the recorded computed task', async () => {
    const deadLetters = await sql<{ id: string; last_error: string | null; trace_data: unknown }>\`
      select "id", "last_error", "trace_data"
      from "computed_update_dead_letter"
      order by "failed_at" desc
      limit 1
    \`.execute(testContainer.dataDb);

    const lastError = deadLetters.rows[0]?.last_error ?? null;
${assertion}
  }, 120_000);
});
`;
};
