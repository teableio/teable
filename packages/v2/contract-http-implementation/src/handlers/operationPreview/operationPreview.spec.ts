import {
  PreviewPlannerRegistry,
  type IOperationPreviewService,
  type IPreviewPlanner,
  type OperationPreview,
  OperationPreviewService,
} from '@teable/v2-command-explain';
import { ActorId, domainError, type IExecutionContext } from '@teable/v2-core';
import { err, ok } from 'neverthrow';
import { describe, expect, it, vi } from 'vitest';

import {
  executeOperationPreviewCapabilitiesEndpoint,
  executeOperationPreviewEndpoint,
} from './operationPreview';

const context: IExecutionContext = {
  actorId: ActorId.create('usrPreview')._unsafeUnwrap(),
};

const preview: OperationPreview = {
  operation: 'table.delete',
  outcome: 'incomplete',
  effects: [],
  blockers: [],
  warnings: [{ code: 'table.delete.authorization_scope_unavailable' }],
  coverage: { known: ['target-table'], unknown: ['dependent-resource-authorization'] },
  complexity: null,
  authorization: 'not-applicable',
  observedAt: '2026-10-27T10:00:00.000Z',
  consistency: 'best-effort',
  requestDigest: `sha256:${'a'.repeat(64)}`,
  implementation: {
    plannerVersion: 'table-delete-v1',
    executionPath: 'DeleteTableCommand/TableDeletionPreparationService',
  },
};

describe('operation preview HTTP handlers', () => {
  it('calls the canonical service exactly once and preserves an incomplete preview', async () => {
    const service = {
      preview: vi.fn().mockResolvedValue(ok(preview)),
    } as unknown as IOperationPreviewService;
    const request = {
      operation: 'table.delete',
      input: { baseId: 'bseA', tableId: 'tblA' },
      options: { detail: 'full' as const },
    };

    const result = await executeOperationPreviewEndpoint(context, request, service);

    expect(result).toEqual({ status: 200, body: { ok: true, data: preview } });
    expect(service.preview).toHaveBeenCalledOnce();
    expect(service.preview).toHaveBeenCalledWith(context, request);
  });

  it.each([
    [
      'preview.operation.unsupported',
      domainError.validation({
        code: 'preview.operation.unsupported',
        message: 'Operation preview is not supported for future.operation',
      }),
    ],
    [
      'preview.table.delete.invalid_input',
      domainError.validation({
        code: 'preview.table.delete.invalid_input',
        message: 'Invalid table delete input',
      }),
    ],
  ])('preserves the stable %s DomainError mapping', async (code, failure) => {
    const service = {
      preview: vi.fn().mockResolvedValue(err(failure)),
    } as unknown as IOperationPreviewService;

    const result = await executeOperationPreviewEndpoint(
      context,
      { operation: 'future.operation', input: {} },
      service
    );

    expect(result.status).toBe(400);
    expect(result.body).toMatchObject({ ok: false, error: { code } });
    expect(service.preview).toHaveBeenCalledOnce();
  });

  it('surfaces unsupported and registered-parser validation codes from the real service', async () => {
    const planner = {
      operation: 'table.delete',
      plannerVersion: 'table-delete-v1',
      executionPath: 'DeleteTableCommand',
      preview: vi.fn(),
    } as unknown as IPreviewPlanner<unknown>;
    const registry = PreviewPlannerRegistry.create([
      {
        operation: 'table.delete',
        parseInput: () =>
          err(
            domainError.validation({
              code: 'preview.table.delete.invalid_input',
              message: 'Invalid table delete input',
            })
          ),
        planner,
        capability: {
          canonicalWriteRoute: 'DELETE /tables/delete',
          supportLevel: 'partial',
          requiredPermissionScope: 'table.delete',
          detailLevels: ['summary', 'full'],
          limitations: [],
        },
      },
    ])._unsafeUnwrap();
    const service = new OperationPreviewService(registry);

    const unsupported = await executeOperationPreviewEndpoint(
      context,
      { operation: 'future.operation', input: {} },
      service
    );
    const invalid = await executeOperationPreviewEndpoint(
      context,
      { operation: 'table.delete', input: {} },
      service
    );

    expect(unsupported.body).toMatchObject({
      ok: false,
      error: { code: 'preview.operation.unsupported' },
    });
    expect(invalid.body).toMatchObject({
      ok: false,
      error: { code: 'preview.table.delete.invalid_input' },
    });
    expect(planner.preview).not.toHaveBeenCalled();
  });

  it('returns capabilities generated by the dispatch registry without invoking a planner', () => {
    const planner = {
      operation: 'table.delete',
      plannerVersion: 'table-delete-v1',
      executionPath: 'DeleteTableCommand/TableDeletionPreparationService',
      preview: vi.fn(),
    } as unknown as IPreviewPlanner<unknown>;
    const registry = PreviewPlannerRegistry.create([
      {
        operation: 'table.delete',
        parseInput: (input: unknown) => ok(input),
        planner,
        capability: {
          canonicalWriteRoute: 'DELETE /tables/delete',
          supportLevel: 'partial',
          requiredPermissionScope: 'table.delete',
          detailLevels: ['summary', 'full'],
          limitations: ['Host trash retention requires a host adapter.'],
        },
      },
    ])._unsafeUnwrap();

    const result = executeOperationPreviewCapabilitiesEndpoint(registry);

    expect(result).toEqual({
      status: 200,
      body: {
        ok: true,
        data: [
          {
            operation: 'table.delete',
            canonicalWriteRoute: 'DELETE /tables/delete',
            supportLevel: 'partial',
            requiredPermissionScope: 'table.delete',
            detailLevels: ['summary', 'full'],
            limitations: ['Host trash retention requires a host adapter.'],
          },
        ],
      },
    });
    expect(planner.preview).not.toHaveBeenCalled();
  });
});
