import type {
  IOperationPreviewService,
  OperationPreviewRequest,
  PreviewPlannerRegistry,
} from '@teable/v2-command-explain';
import {
  mapDomainErrorToHttpError,
  mapDomainErrorToHttpStatus,
  type HttpErrorStatus,
  type IApiErrorResponseDto,
  type IOperationPreviewCapabilitiesOkResponseDto,
  type IOperationPreviewOkResponseDto,
  type IOperationPreviewRequestDto,
} from '@teable/v2-contract-http';
import type { IExecutionContext } from '@teable/v2-core';

export type IOperationPreviewEndpointResult =
  | { readonly status: 200; readonly body: IOperationPreviewOkResponseDto }
  | { readonly status: HttpErrorStatus; readonly body: IApiErrorResponseDto };

export type IOperationPreviewCapabilitiesEndpointResult = {
  readonly status: 200;
  readonly body: IOperationPreviewCapabilitiesOkResponseDto;
};

/** Transport-only adapter; the registered planner owns input validation and all preview logic. */
export const executeOperationPreviewEndpoint = async (
  context: IExecutionContext,
  input: IOperationPreviewRequestDto,
  service: IOperationPreviewService
): Promise<IOperationPreviewEndpointResult> => {
  const result = await service.preview(context, input as OperationPreviewRequest);
  if (result.isErr()) {
    return {
      status: mapDomainErrorToHttpStatus(result.error),
      body: { ok: false, error: mapDomainErrorToHttpError(result.error) },
    };
  }

  return {
    status: 200,
    body: { ok: true, data: result.value },
  };
};

/** Capability data is generated by the same registry used for preview dispatch. */
export const executeOperationPreviewCapabilitiesEndpoint = (
  registry: PreviewPlannerRegistry
): IOperationPreviewCapabilitiesEndpointResult => ({
  status: 200,
  body: { ok: true, data: registry.capabilities() },
});
